import {
  keepPreviousData,
  useInfiniteQuery,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query';
import type {
  OrderCreate,
  OrderDto,
  OrderListQuery,
  OrderSummaryDto,
  Page,
  PayResponse,
  ReturnCreate,
} from '@shop/shared';
import { apiFetch } from '@/shared/api/client';
import { toQueryString } from '@/shared/lib/query-string';
import { orderRefetchInterval } from '../model/refresh';

export type OrderFilters = Partial<Pick<OrderListQuery, 'status' | 'from' | 'to' | 'q'>>;

export const ordersKey = (f: OrderFilters) => ['orders', f] as const;
export const orderKey = (id: string) => ['order', id] as const;

export function useOrders(filters: OrderFilters, pageSize = 20) {
  return useInfiniteQuery({
    queryKey: ordersKey(filters),
    initialPageParam: undefined as string | undefined,
    queryFn: ({ pageParam }) =>
      apiFetch<Page<OrderSummaryDto>>(
        `/orders${toQueryString({ ...filters, limit: pageSize, cursor: pageParam })}`,
      ),
    getNextPageParam: (last) => last.nextCursor ?? undefined,
    placeholderData: keepPreviousData,
  });
}

export function useOrder(id: string) {
  return useQuery({
    queryKey: orderKey(id),
    queryFn: () => apiFetch<OrderDto>(`/orders/${id}`),
    // the page updates itself (payment confirmed, late notification, refund done) - no reload needed
    refetchInterval: (q) => orderRefetchInterval(q.state.data),
    refetchIntervalInBackground: true,
  });
}

function useOrderMutation<V>(id: string, fn: (v: V) => Promise<OrderDto>) {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: fn,
    onSuccess: (order) => {
      qc.setQueryData(orderKey(id), order);
      void qc.invalidateQueries({ queryKey: ['orders'] });
    },
    // a refused action (409: "it shipped meanwhile") means the screen is out of date: show the real state
    onError: () => void qc.invalidateQueries({ queryKey: orderKey(id) }),
  });
}

export const useCancelOrder = (id: string) =>
  useOrderMutation(id, () =>
    apiFetch<OrderDto>(`/orders/${id}/cancel`, { method: 'POST', body: {} }),
  );
export const useCreateReturn = (id: string) =>
  useOrderMutation(id, (body: ReturnCreate) =>
    apiFetch<OrderDto>(`/orders/${id}/returns`, { method: 'POST', body }),
  );

export function usePayOrder(id: string) {
  return useMutation({
    mutationFn: (returnUrl: string) =>
      apiFetch<PayResponse>(`/orders/${id}/pay`, { method: 'POST', body: { returnUrl } }),
  });
}

/**
 * Creates the order. The Idempotency-Key is generated by the CALLER once per checkout attempt, so a
 * double click or a retry after a dropped connection sends the SAME key and yields the SAME order.
 */
export function useCreateOrder() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: ({ body, key }: { body: OrderCreate; key: string }) =>
      apiFetch<OrderDto>('/orders', { method: 'POST', body, headers: { 'Idempotency-Key': key } }),
    onSuccess: (order) => {
      qc.setQueryData(orderKey(order.id), order);
      void qc.invalidateQueries({ queryKey: ['cart'] });
      void qc.invalidateQueries({ queryKey: ['orders'] });
    },
  });
}

export function useChangeOrderStatus() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: ({ id, status }: { id: string; status: 'shipped' | 'delivered' }) =>
      apiFetch<OrderDto>(`/orders/${id}/status`, { method: 'PATCH', body: { status } }),
    onSuccess: (order) => {
      qc.setQueryData(orderKey(order.id), order);
      void qc.invalidateQueries({ queryKey: ['orders'] });
    },
  });
}
